"""Generate the dummy backtesting source workbook (``backtesting_results.xlsx``).

Produces five facility-grain result sheets -- ``results.pd``, ``results.pd_crr``,
``results.lgd``, ``results.ead`` and ``results.nco`` -- carrying model
projections against which realised outcomes can be backtested.

Run from the repository root (no package imports, so the working directory does
not matter)::

    .venv/bin/python source_data/generate_backtesting_data.py

The output is fully deterministic: the same ``SEED`` always yields a
byte-comparable value set, so ``verify_backtesting.py``'s tolerances and the
error-structure assertions are stable across regenerations.

Design decisions that are not obvious from the column list are documented in
``Backtesting_Workbook_Guide.md``; the three that shape the whole file are:

* **Quarter 0 is the realised anchor.** Each Month End Snapshot carries
  ``Quarter`` 0..9. Quarter 0 holds the *observed* value at the snapshot date
  and is therefore identical across all three scenarios and both J/N flags;
  Quarters 1..9 are projections carrying the injected error structure. This
  mirrors the SAAS convention already in the repo (``Quarter <= 0`` is history,
  ``>= 1`` is projection).
* **``results.pd`` and ``results.pd_crr`` are the same structure over different
  populations.** They are not two views of one facility -- they are the PD
  source for *disjoint* halves of the portfolio, split by which PD model owns
  the facility: ``PD_model_a`` rows land on ``results.pd`` and ``PD_model_b``
  rows on ``results.pd_crr``. Both carry an identical column layout and a PD
  generated by the same machinery, so the portfolio's PD is the *union* of the
  two sheets and neither sheet alone covers it.
* **The PD population follows the model catalogue.** ``model_names`` in
  ``dummy_mev_data.xlsx`` says which segments each PD model covers, and the
  facilities generated here match it, so the dashboard's Segment/Model cascade
  can follow the catalogue without ever offering a combination that has no rows.
  LGD and EAD are *not* aligned that way: the catalogue confines them to single
  segments, which would leave no segment with a full PD+LGD+EAD triple and make
  exposure weighting and the NCO identity uncomputable.
* **Exposure lives only on ``results.ead``.** The PD/PD-CRR/LGD sheets carry no
  EAD column by design, so exposure weighting requires a join on the run
  identity *excluding* ``Model Name`` (a facility's PD model differs from its
  EAD model). Every facility is assigned exactly one model per metric, which
  guarantees that join is 1:1 and cannot fan out.

``results.lgd``, ``results.ead`` and ``results.nco`` each cover the **full**
population, since every facility needs an exposure, a loss rate and a
charge-off regardless of where its PD came from. ``NCO`` is therefore
``coalesce(pd, pd_crr) x LGD x EAD`` -- reconciling it requires reading both PD
sheets.
"""

from __future__ import annotations

import datetime as dt
import math
import zlib
from pathlib import Path

import numpy as np
from openpyxl import Workbook

SEED = 20260909
OUTPUT_PATH = Path(__file__).resolve().parent / "backtesting_results.xlsx"

# --- Dimensions -------------------------------------------------------------
# Segment / model / cycle vocabulary is deliberately identical to the
# ``model_names`` sheet of ``dummy_mev_data.xlsx`` so the Backtesting dashboard's
# filters line up with Monitoring's and SAAS's rather than introducing a
# parallel set of names for the same things.
# Segments carried by this workbook. O&M is deliberately absent: the model
# catalogue (``model_names`` in dummy_mev_data.xlsx) has no PD model covering
# it, and a facility with no PD cannot be backtested.
SEGMENTS = ("Cyclical", "Defensive")
PD_MODELS = ("PD_model_a", "PD_model_b")

# Which segments each PD model covers, per the ``model_names`` catalogue. The
# backtesting population is generated to match, so the dashboard's Segment/Model
# cascade can follow the catalogue and never offer an empty combination.
PD_MODEL_SEGMENTS = {
    "PD_model_a": ("Cyclical",),
    "PD_model_b": ("Cyclical", "Defensive"),
}
LGD_MODELS = ("LGD_model_a", "LGD_model_b")
EAD_MODELS = ("EAD_model_a", "EAD_model_b")

# Which PD model's facilities each PD sheet carries. This is what makes the two
# sheets disjoint populations rather than two views of the same facility.
PD_SHEET_MODEL = {"results.pd": "PD_model_a", "results.pd_crr": "PD_model_b"}
SCENARIOS = ("Base", "Adverse", "Severe")
JN_FLAGS = ("J", "N")
LOSS_METHOD = "Expected Loss"

FACILITIES_PER_SEGMENT = 40
N_SNAPSHOTS = 9
N_PROJECTION_QUARTERS = 9          # Quarters 1..9; Quarter 0 is the anchor
N_QUARTERS = N_PROJECTION_QUARTERS + 1

# Nine quarter-end snapshots, 2023Q1 .. 2025Q1.
FIRST_SNAPSHOT = dt.date(2023, 3, 31)

# Snapshots on or before this date belong to the earlier cycle. Run For is a
# deterministic function of the snapshot, so it never affects the exposure join.
CYCLE_SPLIT_DATE = dt.date(2024, 6, 30)
EARLY_CYCLE = "CCAR 2025"
LATE_CYCLE = "CCAR 2026"

# --- Injected error structure ----------------------------------------------
# Forecast = realised(target quarter) x (1 + vintage_shift + bias(q) + noise(q)),
# with bias and noise both scaled by the J/N and segment factors below, then
# multiplied by the scenario overlay. Quarter 0 bypasses all of it.
ERROR_SPECS = {
    #         noise sd = sd_base + sd_slope * q ; bias = bias_slope * max(0, q - BIAS_FREE_HORIZON)
    # There is no separate "pd_crr" spec: both PD sheets are drawn from this one
    # PD series and then split by population, so the error structure is
    # identical on either side of the partition.
    "pd":  {"sd_base": 0.030, "sd_slope": 0.022, "bias_slope": -0.012, "vintage_shift": 0.35},
    "lgd": {"sd_base": 0.020, "sd_slope": 0.014, "bias_slope": -0.008, "vintage_shift": 0.22},
    "ead": {"sd_base": 0.018, "sd_slope": 0.010, "bias_slope": 0.000, "vintage_shift": 0.12},
}
BIAS_FREE_HORIZON = 2              # no optimistic bias at q <= 2

# J-flagged (judgemental / post-overlay) runs are more accurate than N.
JN_ACCURACY_FACTOR = {"J": 0.65, "N": 1.00}

# One segment is materially worse than the other. Cyclical carries it now that
# O&M is out of scope -- a cyclical book missing harder is the plausible story.
SEGMENT_ERROR_FACTOR = {"Cyclical": 2.20, "Defensive": 0.85}

# One deliberately bad vintage, off across every one of its horizons.
BAD_VINTAGE_INDEX = 4              # the 5th snapshot -> 2024-03-31

# Scenario overlay: conservatism layered on top of the Base path, growing with
# horizon. This is a scenario effect, not model error -- backtesting compares
# Base against realised, and the other two exist as context.
SCENARIO_SLOPE = {"Base": 0.000, "Adverse": 0.045, "Severe": 0.100}
# How much of the overlay each metric absorbs (PD is fully scenario-sensitive;
# exposure barely at all).
SCENARIO_SENSITIVITY = {"pd": 1.00, "lgd": 0.35, "ead": 0.15}

# Segment risk levels (levels, not errors).
SEGMENT_PD_LEVEL = {"Cyclical": 1.30, "Defensive": 0.70}

# --- Re-run / dedupe fixtures ----------------------------------------------
# Each entry names a (segment, snapshot index, scenario, J/N flag) whose rows are
# emitted twice: a superseded first attempt with an earlier Execution Datetime
# and perturbed values, then the canonical re-run. Keeping max(Execution
# Datetime) per run key must recover exactly the canonical rows.
#
# Deliberate property: every sheet scales its superseded values by the same
# factor, so a superseded NCO row is 0.94x its canonical value while the
# superseded PD/LGD/EAD product is 0.94^3x. Superseded rows therefore do *not*
# satisfy NCO = PD x LGD x EAD. That is intentional -- it means any consumer
# that reconciles before deduping fails loudly instead of quietly averaging a
# botched first attempt into the answer.
DUPLICATE_RUNS = (
    ("Cyclical", 2, "Base", "N"),
    ("Defensive", 5, "Severe", "J"),
    ("Defensive", 8, "Adverse", "N"),
)
SUPERSEDED_VALUE_FACTOR = 0.94
SUPERSEDED_DAYS_EARLIER = 2

VALUE_FLOOR = 1e-4
VALUE_CEIL = 0.9999
EAD_FLOOR = 1_000.0

SHEET_COLUMNS = {
    "results.pd": (
        "Segment Name", "Model Name", "Month End Snapshot", "Run For", "Scenario",
        "J/N Flag", "Facility ID", "Credit Instrument ID", "Quarter", "PD Value",
        "Execution Datetime",
    ),
    "results.pd_crr": (
        "Segment Name", "Model Name", "Month End Snapshot", "Run For", "Scenario",
        "J/N Flag", "Facility ID", "Credit Instrument ID", "Quarter", "PD Value",
        "Execution Datetime",
    ),
    "results.lgd": (
        "Segment Name", "Model Name", "Month End Snapshot", "Run For", "Scenario",
        "J/N Flag", "Facility ID", "Credit Instrument ID", "Quarter", "LGD Value",
        "Execution Datetime",
    ),
    "results.ead": (
        "Segment Name", "Model Name", "Month End Snapshot", "Run For", "Scenario",
        "J/N Flag", "Facility ID", "Credit Instrument ID", "Quarter", "EAD Value",
        "Execution Datetime",
    ),
    "results.nco": (
        "Segment Name", "PD Model Name", "LGD Model Name", "EAD Model Name",
        "Month End Snapshot", "Run For", "Scenario", "J/N Flag", "Loss Method",
        "Facility ID", "Credit Instrument ID", "Quarter", "NCO Value",
        "Execution Datetime",
    ),
}


# ---------------------------------------------------------------------------
# Calendar helpers
# ---------------------------------------------------------------------------


def _quarter_end(base: dt.date, quarters_ahead: int) -> dt.date:
    """The month-end date ``quarters_ahead`` quarters after ``base``."""
    month_index = (base.year * 12 + (base.month - 1)) + 3 * quarters_ahead
    year, month = divmod(month_index, 12)
    month += 1
    if month == 12:
        return dt.date(year, 12, 31)
    first_of_next = dt.date(year + (month // 12), (month % 12) + 1, 1)
    return first_of_next - dt.timedelta(days=1)


SNAPSHOT_DATES = tuple(_quarter_end(FIRST_SNAPSHOT, i) for i in range(N_SNAPSHOTS))


def _run_for(snapshot: dt.date) -> str:
    return EARLY_CYCLE if snapshot <= CYCLE_SPLIT_DATE else LATE_CYCLE


def _stable_hash(*parts) -> int:
    """A process-independent hash.

    ``hash()`` on strings is salted per interpreter run (PYTHONHASHSEED), so
    using it here would make the execution timestamps differ between
    regenerations of an otherwise identical workbook.
    """
    return zlib.crc32("|".join(str(part) for part in parts).encode("utf-8"))


_EXECUTION_CACHE: dict[tuple, dt.datetime] = {}


def _execution_datetime(snapshot: dt.date, segment: str, scenario: str, jn_flag: str) -> dt.datetime:
    """A stable per-run execution timestamp, a few days after the snapshot.

    Deterministic in the run's own identity so regenerating the workbook does not
    reshuffle which execution is the latest. Note it deliberately does not vary
    with ``Model Name``: one execution produces every model's rows for a given
    segment / snapshot / scenario / flag.
    """
    key = (snapshot, segment, scenario, jn_flag)
    cached = _EXECUTION_CACHE.get(key)
    if cached is not None:
        return cached
    spread = (_stable_hash(segment, scenario, jn_flag) % 4) + 3        # 3..6 days later
    hour = 6 + (_stable_hash(scenario, jn_flag, segment) % 11)        # 06:00..16:00
    minute = (_stable_hash(segment, snapshot.toordinal(), jn_flag) % 4) * 15
    stamp = dt.datetime.combine(snapshot, dt.time(hour, minute)) + dt.timedelta(days=spread)
    _EXECUTION_CACHE[key] = stamp
    return stamp


