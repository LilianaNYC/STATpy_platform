# Facility population
# ---------------------------------------------------------------------------


def build_facilities(rng: np.random.Generator) -> list[dict]:
    """The facility x credit-instrument population, shared by all five sheets.

    Each facility is assigned exactly one PD, LGD and EAD model. That is what
    makes the exposure join 1:1: a PD row and its EAD row share every join field
    except ``Model Name``, and no facility is claimed by two EAD models.
    """
    facilities: list[dict] = []
    for segment in SEGMENTS:
        prefix = {"Cyclical": "CYC", "Defensive": "DEF"}[segment]
        for n in range(1, FACILITIES_PER_SEGMENT + 1):
            facility_id = f"F-{prefix}-{n:03d}"
            # Roughly 30% of facilities carry a second credit instrument, so the
            # grain is genuinely facility x instrument rather than facility only.
            instrument_count = 2 if n % 10 < 3 else 1
            # Catalogue-driven: only models whose ``model_names`` entry covers
            # this segment may score its facilities. Cyclical is served by both
            # PD models and splits between them; Defensive is PD_model_b's alone.
            eligible = [
                model for model in PD_MODELS if segment in PD_MODEL_SEGMENTS[model]
            ]
            pd_model = eligible[n % len(eligible)]
            lgd_model = LGD_MODELS[(n // 2) % len(LGD_MODELS)]
            ead_model = EAD_MODELS[(n // 3) % len(EAD_MODELS)]
            for instrument in range(1, instrument_count + 1):
                facilities.append({
                    "segment": segment,
                    "facility_id": facility_id,
                    "instrument_id": f"CI-{prefix}-{n:03d}-{instrument}",
                    "pd_model": pd_model,
                    "lgd_model": lgd_model,
                    "ead_model": ead_model,
                    "base_pd": float(np.clip(rng.lognormal(-3.95, 0.55), 0.002, 0.20)),
                    "base_lgd": float(np.clip(rng.normal(0.42, 0.11), 0.15, 0.78)),
                    "base_ead": float(np.clip(rng.lognormal(14.2, 0.95), 2.0e5, 4.0e7)),
                })
    return facilities


def build_realised_paths(facilities: list[dict], rng: np.random.Generator) -> dict[str, np.ndarray]:
    """The 'true' realised path per facility-instrument over calendar quarters.

    Indexed ``[pair, t]`` where ``t`` is a calendar-quarter offset from the first
    snapshot. Paths run to ``N_SNAPSHOTS + N_PROJECTION_QUARTERS`` because the
    last vintage forecasts nine quarters past the final snapshot -- those targets
    have no realised anchor, exactly as they would not in production.
    """
    n_pairs = len(facilities)
    n_t = N_SNAPSHOTS + N_PROJECTION_QUARTERS

    # A gentle systemic credit cycle shared by every facility.
    t_axis = np.arange(n_t)
    cycle = 1.0 + 0.35 * np.sin(2 * math.pi * (t_axis + 2) / 14.0)

    base_pd = np.array([f["base_pd"] for f in facilities])[:, None]
    base_lgd = np.array([f["base_lgd"] for f in facilities])[:, None]
    base_ead = np.array([f["base_ead"] for f in facilities])[:, None]
    seg_level = np.array([SEGMENT_PD_LEVEL[f["segment"]] for f in facilities])[:, None]

    pd_path = base_pd * seg_level * cycle[None, :] * (1.0 + rng.normal(0, 0.10, (n_pairs, n_t)))
    pd_path = np.clip(pd_path, VALUE_FLOOR, VALUE_CEIL)

    # LGD moves with the cycle, but far less than PD.
    lgd_cycle = 1.0 + 0.12 * (cycle - 1.0) / 0.35
    lgd_path = base_lgd * lgd_cycle[None, :] * (1.0 + rng.normal(0, 0.05, (n_pairs, n_t)))
    lgd_path = np.clip(lgd_path, VALUE_FLOOR, VALUE_CEIL)

    # Exposure drifts up slowly and is close to cycle-neutral.
    ead_path = base_ead * (1.0 + 0.004 * t_axis)[None, :] * (1.0 + rng.normal(0, 0.03, (n_pairs, n_t)))
    ead_path = np.maximum(ead_path, EAD_FLOOR)

    return {"pd": pd_path, "lgd": lgd_path, "ead": ead_path}


# ---------------------------------------------------------------------------
# Row construction
# ---------------------------------------------------------------------------


def _index_arrays(n_pairs: int) -> dict[str, np.ndarray]:
    """Index arrays for the (snapshot, scenario, flag, pair, quarter) cross product.

    Quarter varies fastest, so each facility's ten-quarter path is contiguous.
    """
    n_sc, n_jn = len(SCENARIOS), len(JN_FLAGS)
    block = n_sc * n_jn * n_pairs * N_QUARTERS
    return {
        "s": np.repeat(np.arange(N_SNAPSHOTS), block),
        "sc": np.tile(np.repeat(np.arange(n_sc), n_jn * n_pairs * N_QUARTERS), N_SNAPSHOTS),
        "jn": np.tile(np.repeat(np.arange(n_jn), n_pairs * N_QUARTERS), N_SNAPSHOTS * n_sc),
        "p": np.tile(np.repeat(np.arange(n_pairs), N_QUARTERS), N_SNAPSHOTS * n_sc * n_jn),
        "q": np.tile(np.arange(N_QUARTERS), N_SNAPSHOTS * n_sc * n_jn * n_pairs),
    }


def _forecast_values(
    metric: str,
    realised: np.ndarray,
    idx: dict[str, np.ndarray],
    facilities: list[dict],
    noise: np.ndarray,
) -> np.ndarray:
    """Apply the injected error structure to one metric's realised path.

    ``noise`` is pre-drawn per (pair, snapshot, quarter, flag) and deliberately
    carries no scenario axis: the scenario overlay is a deterministic
    conservatism layer, not a source of forecast error.
    """
    spec = ERROR_SPECS[metric]
    q = idx["q"]
    s = idx["s"]

    target_t = s + q
    base = realised[idx["p"], target_t]

    seg_factor = np.array([SEGMENT_ERROR_FACTOR[f["segment"]] for f in facilities])[idx["p"]]
    jn_factor = np.array([JN_ACCURACY_FACTOR[flag] for flag in JN_FLAGS])[idx["jn"]]
    accuracy = seg_factor * jn_factor

    # Optimistic (loss-under-forecasting) drift that only bites past the near term.
    bias = spec["bias_slope"] * np.maximum(0, q - BIAS_FREE_HORIZON) * accuracy
    drawn = noise[idx["p"], s, q, idx["jn"]] * (spec["sd_base"] + spec["sd_slope"] * q) * accuracy
    vintage = np.where(s == BAD_VINTAGE_INDEX, spec["vintage_shift"], 0.0)

    multiplier = 1.0 + vintage + bias + drawn

    scenario_slope = np.array([SCENARIO_SLOPE[name] for name in SCENARIOS])[idx["sc"]]
    overlay = 1.0 + scenario_slope * q * SCENARIO_SENSITIVITY[metric]

    values = base * multiplier * overlay

    # Quarter 0 is the realised anchor: no error, no scenario overlay, identical
    # across all three scenarios and both J/N flags.
    anchor = q == 0
    values[anchor] = base[anchor]

    if metric == "ead":
        return np.maximum(values, EAD_FLOOR)
    return np.clip(values, VALUE_FLOOR, VALUE_CEIL)


def build_value_columns(facilities: list[dict], rng: np.random.Generator) -> tuple[dict, dict]:
    """Return ``(index_arrays, {metric: values})`` for the full cross product."""
    realised = build_realised_paths(facilities, rng)
    idx = _index_arrays(len(facilities))

    noise_shape = (len(facilities), N_SNAPSHOTS, N_QUARTERS, len(JN_FLAGS))
    values = {
        metric: _forecast_values(metric, realised[metric], idx, facilities, rng.normal(0, 1, noise_shape))
        for metric in ("pd", "lgd", "ead")
    }
    # NCO is the expected-loss identity applied to the *emitted* (clipped) values,
    # so the reconciliation in verify_backtesting.py is exact to float precision.
    # There is one PD series, so this is coalesce(pd, pd_crr) by construction:
    # whichever PD sheet a facility lands on, its NCO uses that same value.
    values["nco"] = values["pd"] * values["lgd"] * values["ead"]
    return idx, values


def _is_duplicate_run(segment: str, snapshot_index: int, scenario: str, jn_flag: str) -> bool:
    return (segment, snapshot_index, scenario, jn_flag) in DUPLICATE_RUNS


def build_sheet_rows(
    sheet: str,
    facilities: list[dict],
    idx: dict[str, np.ndarray],
    values: dict[str, np.ndarray],
) -> list[tuple]:
    """Materialise one sheet's rows, superseded duplicates included.

    Superseded rows are emitted *before* their canonical re-run so file order
    tells the same story the timestamps do.

    The two PD sheets read the same ``values["pd"]`` array but each keeps only
    the facilities its own PD model owns, which is what makes their populations
    disjoint. Every other sheet keeps the full population.
    """
    metric = {
        "results.pd": "pd", "results.pd_crr": "pd", "results.lgd": "lgd",
        "results.ead": "ead", "results.nco": "nco",
    }[sheet]
    value_array = values[metric]
    is_nco = sheet == "results.nco"
    model_key = {
        "results.pd": "pd_model", "results.pd_crr": "pd_model",
        "results.lgd": "lgd_model", "results.ead": "ead_model",
    }.get(sheet)

    # Facility indices this sheet carries (all of them, unless it is a PD sheet).
    sheet_pd_model = PD_SHEET_MODEL.get(sheet)
    if sheet_pd_model is None:
        included = None
    else:
        included = {i for i, f in enumerate(facilities) if f["pd_model"] == sheet_pd_model}

    segments = [f["segment"] for f in facilities]
    facility_ids = [f["facility_id"] for f in facilities]
    instrument_ids = [f["instrument_id"] for f in facilities]

    canonical: list[tuple] = []
    superseded: list[tuple] = []

    s_arr, sc_arr, jn_arr, p_arr, q_arr = idx["s"], idx["sc"], idx["jn"], idx["p"], idx["q"]

    for row in range(len(value_array)):
        pair = int(p_arr[row])
        if included is not None and pair not in included:
            continue
        snapshot_index = int(s_arr[row])
        snapshot = SNAPSHOT_DATES[snapshot_index]
        segment = segments[pair]
        scenario = SCENARIOS[int(sc_arr[row])]
        jn_flag = JN_FLAGS[int(jn_arr[row])]
        run_for = _run_for(snapshot)
        executed = _execution_datetime(snapshot, segment, scenario, jn_flag)
        value = float(value_array[row])
        quarter = int(q_arr[row])
        facility = facilities[pair]

        if is_nco:
            head = (
                segment, facility["pd_model"], facility["lgd_model"], facility["ead_model"],
                snapshot, run_for, scenario, jn_flag, LOSS_METHOD,
            )
        else:
            head = (segment, facility[model_key], snapshot, run_for, scenario, jn_flag)

        tail = (facility_ids[pair], instrument_ids[pair], quarter)
        canonical.append((*head, *tail, value, executed))

        if _is_duplicate_run(segment, snapshot_index, scenario, jn_flag):
            superseded.append((
                *head, *tail,
                value * SUPERSEDED_VALUE_FACTOR,
                executed - dt.timedelta(days=SUPERSEDED_DAYS_EARLIER),
            ))

    return superseded + canonical


# ---------------------------------------------------------------------------
# Workbook writing
# ---------------------------------------------------------------------------


def write_workbook(sheets: dict[str, list[tuple]], path: Path) -> None:
    """Write every sheet with openpyxl's write-only mode.

    Write-only keeps memory flat across ~430k rows; the normal grid would hold
    a cell object per value.
    """
    workbook = Workbook(write_only=True)
    for sheet_name, rows in sheets.items():
        worksheet = workbook.create_sheet(title=sheet_name)
        worksheet.append(list(SHEET_COLUMNS[sheet_name]))
        for row in rows:
            worksheet.append(row)
    workbook.save(path)


def main() -> None:
    rng = np.random.default_rng(SEED)
    facilities = build_facilities(rng)
    idx, values = build_value_columns(facilities, rng)

    print(f"Facility x instrument pairs : {len(facilities):,}")
    print(f"Snapshots                   : {N_SNAPSHOTS} ({SNAPSHOT_DATES[0]} .. {SNAPSHOT_DATES[-1]})")
    print(f"Quarters per snapshot       : {N_QUARTERS} (0 = realised anchor, 1..{N_PROJECTION_QUARTERS} = projections)")
    print(f"Scenarios / flags           : {len(SCENARIOS)} / {len(JN_FLAGS)}")
    print()

    sheets: dict[str, list[tuple]] = {}
    for sheet_name in SHEET_COLUMNS:
        rows = build_sheet_rows(sheet_name, facilities, idx, values)
        sheets[sheet_name] = rows
        print(f"  {sheet_name:<16} {len(rows):>8,} rows")

    print(f"\nWriting {OUTPUT_PATH} ...")
    write_workbook(sheets, OUTPUT_PATH)
    size_mb = OUTPUT_PATH.stat().st_size / (1024 * 1024)
    print(f"Done. {size_mb:.1f} MB")


if __name__ == "__main__":
    main()
